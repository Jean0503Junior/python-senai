frutas = ["maça", "banana", "laranja", "morango"]

# index()
print("index(): ", frutas.index("banana"))

# count()
print("count(): ", frutas.count("banana"))

# Append()
frutas.append("uva")
print("Append(): ", frutas)

# Extend()
outras_frutas = ["Abacaxi", "Morango"]
frutas.extend(outras_frutas)
print("Extend(): ", frutas)