# Entrada de dados básicos
n1 = int (input("Digite o primeiro número: "))
n2 = int (input("Digite o segundo número: "))

# Processamento computacional
soma = n1 + n2
subtracao = n1 - n2
divisao = n1 / n2
multi = n1 * n2

# Sáida da informação
print("O resultado da soma dos números é:", soma)
print("O resultado da subtração dos números é:", subtracao)
print("O resultado da divisão dos números é:", divisao)
print("O resultadi da multiplicação dos números é:", multi)
